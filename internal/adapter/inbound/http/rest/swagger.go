//	@title						Authenticity API
//	@description				Identity service. To call protected routes, log in and paste "Bearer <access_token>" in Authorize.
//	@BasePath					/
//	@securityDefinitions.apikey	BearerAuth
//	@in							header
//	@name						Authorization

// One @tag.name per subject, then one x-tagGroups entry per group. The page
// follows the @tag.name order, so keep each group's tags together.

//	@tag.name			Health
//	@tag.description	Service status
//	@tag.name			Auth
//	@tag.description	Login and current user
//	@tag.name			Registration
//	@tag.description	Account creation and activation
//	@tag.name			Password
//	@tag.description	Password reset
//	@tag.name			Sessions
//	@tag.description	Devices logged in to the account
//	@tag.name			Preferences
//	@tag.description	Interface choices of the current user
//	@tag.name			Notifications
//	@tag.description	Security notices for the current user
//	@tag.name			Permissions
//	@tag.description	Resources that roles may be granted
//	@tag.name			Roles
//	@tag.description	Roles, their permissions and members. The admin role cannot be changed
//	@tag.name			Products
//	@tag.description	Product catalog
//	@x-tagGroups		[{"name":"System","tags":["Health"]},{"name":"Identity","tags":["Auth","Registration","Password","Sessions"]},{"name":"Account","tags":["Preferences","Notifications"]},{"name":"Access","tags":["Permissions","Roles"]},{"name":"Catalog","tags":["Products"]}]

var (
	//go:embed swagger.css
	swaggerCSS string
	//go:embed swagger.js
	swaggerJS string
)

// mountSwagger serves the docs generated by `make swagger` at /swagger.
func mountSwagger(app *fiber.App, version string) {
	docs.SwaggerInfo.Version = version
	app.Get("/swagger/*", swaggo.New(swaggo.Config{
		Title:                  "Authenticity API",
		DocExpansion:           "none", // groups start closed, so the page stays readable as it grows
		Filter:                 swaggo.FilterConfig{Enabled: true},
		PersistAuthorization:   true,
		DisplayRequestDuration: true,
		CustomStyle:            template.CSS(swaggerCSS),
		CustomScript:           template.JS(swaggerJS),
		Plugins:                []template.JS{"SwaggerUIBundle.plugins.DownloadUrl", "TagGroups"},
	}))
}
